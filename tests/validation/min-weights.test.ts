import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { exactMatchingWeight } from "../../src/core/decoder/oracle";
import {
  createDecoder,
  decode,
  identity,
  MAX_EDGE_WEIGHT,
  rotatedSurfaceCode,
  WEIGHT_EPSILON_DENOMINATOR,
  WEIGHT_SCALE,
  WEIGHT_SEED,
  type Decoder,
  type StabilizerType,
} from "../../src/core/index";

/**
 * T-V1 — Minimum matching weights equal PyMatching's exactly (docs/spec.md §6 «Pesos mínimos
 * frente a PyMatching»). The fixture docs/validacion/min-weights.json is generated by
 * tools/reference/run.py with the integer weights of src/core/decoder/weights.ts; its
 * format is fixed in tasks/plans/decoder.md §3 and pinned here by an inline sample so
 * that the reader exists before the file does. No statistical tolerance: `toBe`.
 */

interface MinWeightsFixture {
  schema: number;
  generator: string;
  pymatching: string;
  weights: {
    seed: string;
    scale: number;
    epsilonDenominator: number;
    maxEdgeWeight: number;
  };
  cases: {
    d: number;
    type: StabilizerType;
    defects: number[];
    weight: number;
  }[];
}

const FIXTURE = join(process.cwd(), "docs", "validacion", "min-weights.json");

function decoderCache(): (d: number, type: StabilizerType) => Decoder {
  const cache = new Map<string, Decoder>();
  return (d, type) => {
    const key = `${d}${type}`;
    let dec = cache.get(key);
    if (dec === undefined) {
      dec = createDecoder(rotatedSurfaceCode(d), type);
      cache.set(key, dec);
    }
    return dec;
  };
}

const FIXTURE_DISTANCES = [3, 5, 7, 9];
const FIXTURE_TYPES: StabilizerType[] = ["Z", "X"];
/** run.py alternates the types, 2 500 cases per d: 1 250 per (d, type). */
const MIN_CASES_PER_D_AND_TYPE = 1000;

/** Runs every case of a fixture through `decode`; returns the count per `${d}${type}`. */
function checkFixture(fixture: MinWeightsFixture): Map<string, number> {
  expect(fixture.schema).toBe(1);
  expect(fixture.weights.seed.toUpperCase()).toBe(
    `0X${WEIGHT_SEED.toString(16).toUpperCase()}`,
  );
  expect(fixture.weights.scale).toBe(WEIGHT_SCALE);
  expect(fixture.weights.epsilonDenominator).toBe(WEIGHT_EPSILON_DENOMINATOR);
  expect(fixture.weights.maxEdgeWeight).toBe(MAX_EDGE_WEIGHT);
  const decoderOf = decoderCache();
  const perKey = new Map<string, number>();
  for (const c of fixture.cases) {
    const dec = decoderOf(c.d, c.type);
    const m = dec.graph.m;
    const syndrome = new Uint8Array(m);
    for (let k = 0; k < c.defects.length; k++) {
      const i = c.defects[k]!;
      expect(i).toBeGreaterThanOrEqual(0);
      expect(i).toBeLessThan(m);
      if (k > 0) expect(i).toBeGreaterThan(c.defects[k - 1]!); // ascending
      syndrome[i] = 1;
    }
    const total = decode(dec, syndrome, identity(c.d * c.d));
    expect(total, `d = ${c.d} ${c.type} ${JSON.stringify(c.defects)}`).toBe(
      c.weight,
    );
    const key = `${c.d}${c.type}`;
    perKey.set(key, (perKey.get(key) ?? 0) + 1);
  }
  return perKey;
}

describe("T-V1 minimum weights = PyMatching (docs/validacion/min-weights.json)", () => {
  it("inline sample in the fixture format (3 cases of d = 3, weights from the DP oracle)", () => {
    const decoderOf = decoderCache();
    const sampleCases: {
      d: number;
      type: StabilizerType;
      defects: number[];
    }[] = [
      { d: 3, type: "Z", defects: [0, 3] },
      { d: 3, type: "X", defects: [1] },
      { d: 3, type: "Z", defects: [0, 1, 2, 3] },
    ];
    const text = JSON.stringify({
      schema: 1,
      generator: "tools/reference/run.py",
      pymatching: "2.4.0",
      weights: {
        seed: "0x53594E44",
        scale: 16760454,
        epsilonDenominator: 1000,
        maxEdgeWeight: 16777215,
      },
      cases: sampleCases.map((c) => ({
        ...c,
        weight: exactMatchingWeight(decoderOf(c.d, c.type).graph, c.defects),
      })),
    });
    const parsed = JSON.parse(text) as MinWeightsFixture;
    expect(parsed.cases[0]!.weight).toBeGreaterThan(0);
    const counts = checkFixture(parsed);
    expect(counts.get("3Z")).toBe(2);
    expect(counts.get("3X")).toBe(1);
    expect(counts.size).toBe(2);
  });

  it("every case of the fixture decodes to exactly the PyMatching weight", () => {
    // The fixture is committed (generated by `uv run tools/reference/run.py`); a
    // missing file is red, not skipped.
    expect(existsSync(FIXTURE), `${FIXTURE} missing`).toBe(true);
    const fixture = JSON.parse(
      readFileSync(FIXTURE, "utf8"),
    ) as MinWeightsFixture;
    expect(fixture.generator).toBe("tools/reference/run.py");
    expect(fixture.cases.length).toBeGreaterThanOrEqual(10_000);
    const counts = checkFixture(fixture);
    // Per (d, type), not per d: a fixture of one type only would leave the other
    // defect graph (and its boundary) untested while still counting 2 500 per d.
    for (const d of FIXTURE_DISTANCES) {
      for (const type of FIXTURE_TYPES) {
        expect(
          counts.get(`${d}${type}`) ?? 0,
          `cases for d = ${d} ${type}`,
        ).toBeGreaterThanOrEqual(MIN_CASES_PER_D_AND_TYPE);
      }
    }
  });
});
